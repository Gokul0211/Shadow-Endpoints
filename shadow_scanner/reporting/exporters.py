"""
Export a scan report as an OpenAPI 3.0 document or a Postman collection.

Only what the scan observed is written. Nothing is invented: path templates come from the discovered URLs
(`{param}` holes keep their position and get unique names), request bodies and response schemas are not
guessed, and the parameter names the scanner collected (which may be query keys, body fields or RPC procedure
names - the report does not say which) go into `x-observed-parameters`. Each operation carries the scanner's
confidence score and evidence kinds as `x-` extensions so a consumer can filter.

WebSocket endpoints are listed under the top-level `x-websockets`; GraphQL endpoints appear as a POST operation.
"""
import json
import re
import urllib.parse

_HOLE = re.compile(r'\{([^{}/]*)\}')
_METHODS = {'GET', 'POST', 'PUT', 'PATCH', 'DELETE', 'HEAD', 'OPTIONS'}


def _split(url):
    p = urllib.parse.urlsplit(url)
    return f'{p.scheme}://{p.netloc}', p.path or '/'


def _name_holes(path):
    """Give every `{...}` a unique valid parameter name; return (new_path, names)."""
    names, seen = [], {}

    def rename(m):
        base = re.sub(r'\W', '', m.group(1)) or 'param'
        seen[base] = seen.get(base, 0) + 1
        name = base if seen[base] == 1 else f'{base}{seen[base]}'
        names.append(name)
        return '{' + name + '}'

    return _HOLE.sub(rename, path), names


def _rows(report, min_score):
    for e in report.get('endpoints', []):
        if (e.get('confidence_score') or 0) >= min_score and e.get('endpoint'):
            yield e


def to_openapi(report, min_score=0):
    """OpenAPI 3.0.3 dict for a scanner report (dict as written by save_report)."""
    target = (report.get('scan_metadata') or {}).get('target', '')
    servers, paths, websockets = [], {}, []
    auth_seen = False
    for e in _rows(report, min_score):
        base, raw_path = _split(e['endpoint'])
        method = (e.get('method') or 'GET').upper()
        if base not in servers:
            servers.append(base)
        if method == 'WS' or base.startswith(('ws:', 'wss:')):
            websockets.append({'url': e['endpoint'], 'x-confidence': e.get('confidence_score')})
            continue
        if method == 'GRAPHQL':
            method = 'POST'
        if method not in _METHODS:
            continue
        path, names = _name_holes(raw_path)
        op = {
            'summary': f'{method} {raw_path}',
            'parameters': [{'name': n, 'in': 'path', 'required': True, 'schema': {'type': 'string'}} for n in names],
            'responses': {'default': {'description': 'not observed'}},
            'x-confidence': e.get('confidence_score'),
            'x-evidence-kinds': (e.get('origin') or {}).get('evidence_kinds', []),
            'x-method-inferred': bool(e.get('method_inferred')),
        }
        if len(servers) > 1 or base != servers[0]:
            op['servers'] = [{'url': base}]
        if e.get('parameters'):
            op['x-observed-parameters'] = sorted(e['parameters'])
        if e.get('auth_required'):
            op['security'] = [{'bearerAuth': []}] if e.get('auth_method') == 'authorization_header' else [{'cookieAuth': []}]
            auth_seen = True
        slot = paths.setdefault(path, {})
        # the same path on two hosts: keep the higher-scored one in `paths`, the other stays listed by `servers`
        if method.lower() not in slot or (slot[method.lower()].get('x-confidence') or 0) < (op['x-confidence'] or 0):
            slot[method.lower()] = op
    doc = {
        'openapi': '3.0.3',
        'info': {'title': f'Discovered API surface of {target}' if target else 'Discovered API surface',
                 'version': (report.get('scan_metadata') or {}).get('timestamp', ''),
                 'description': 'Generated by Shadow Endpoints from client-side code and observed traffic. '
                                'Operations are not verified contracts; see x-confidence.'},
        'servers': [{'url': s} for s in servers],
        'paths': dict(sorted(paths.items())),
    }
    if auth_seen:
        doc['components'] = {'securitySchemes': {
            'bearerAuth': {'type': 'http', 'scheme': 'bearer'},
            'cookieAuth': {'type': 'apiKey', 'in': 'cookie', 'name': 'session'}}}
    if websockets:
        doc['x-websockets'] = websockets
    return doc


def to_postman(report, min_score=0):
    """Postman collection v2.1 dict: one folder per host, one request per (method, URL)."""
    folders = {}
    for e in _rows(report, min_score):
        method = (e.get('method') or 'GET').upper()
        if method in ('WS',):
            continue
        if method == 'GRAPHQL':
            method = 'POST'
        if method not in _METHODS:
            continue
        base, path = _split(e['endpoint'])
        raw = e['endpoint'].replace('{', ':').replace('}', '')
        item = {'name': f'{method} {path}',
                'request': {'method': method, 'header': [],
                            'url': {'raw': raw, 'host': [urllib.parse.urlsplit(base).netloc],
                                    'path': [s for s in path.split('/') if s]}}}
        if e.get('auth_required'):
            item['request']['auth'] = {'type': 'bearer', 'bearer': [{'key': 'token', 'value': '{{token}}', 'type': 'string'}]}
        folders.setdefault(base, []).append(item)
    return {'info': {'name': 'Shadow Endpoints discovery',
                     'schema': 'https://schema.getpostman.com/json/collection/v2.1.0/collection.json'},
            'item': [{'name': h, 'item': sorted(items, key=lambda i: i['name'])} for h, items in sorted(folders.items())]}


def write_json(doc, path):
    with open(path, 'w', encoding='utf-8') as f:
        json.dump(doc, f, indent=2)
